"""ゲームの手触りを決める数値。

値の横に「なぜこの値か」を書く。理由の無い数値は、次に読んだ人が「仮に置いた値」と
受け取って変えてしまう。理由は原型（`legacy/animal-bomber.html` の注記と
`legacy/animal-bomber-notes.md`）にあるものを持ってきた。原型に理由が書かれていない
値は、そう書いてある。

いまは段階 1 で使うもの（盤面と移動）だけを置いている。爆弾や体力の値は、使う段階で
足す。

1秒あたりで書いた値は、1 tick あたりに直した値もここで持つ。読むときは秒のほうが
分かりやすく、計算に使うのは tick のほうなので、直すのをここ1か所にまとめる。
1 tick あたりの値は秒あたりの値を `TICKS_PER_SECOND` で割って作る（割り算は
IEEE 754 が正確な丸めを求めているので、どの環境でも同じ値になる）。
"""

from typing import Final

from animal_bomber.domain.core.coord import Cell
from animal_bomber.domain.core.tick import TICKS_PER_SECOND

# ------------------------------------------------------------------ 盤面

COLS: Final = 23
ROWS: Final = 17
"""外周の壁を含む、盤面の列と行の数。

本家（15×13）より目を細かくして、開始直後に相手と出会わないようにした（原型の注記）。
"""

SOFT_BLOCK_RATIO: Final = 0.78
"""壊せるブロックを置く確率。

外周・柱・開始位置のまわりを除いた空きマスごとに、この確率で置く。原型の値で、
選んだ理由の記録は無い。
"""

SPAWN_CELLS: Final = (
    Cell(1, 1),
    Cell(COLS - 2, 1),
    Cell(1, ROWS - 2),
    Cell(COLS - 2, ROWS - 2),
)
"""開始位置。外周の壁の内側の四隅で、プレイヤー番号（0〜3）の順に並ぶ。"""

SPAWN_CLEARANCE: Final = 2
"""開始位置から上下左右へ、壊せるブロックを置かずに空けておくマス数。

原型の値。原型の注記は「スタート地点まわりは空ける」だけで、2 という数を選んだ理由の
記録は無い。
"""

# ------------------------------------------------------------------ 移動

BASE_SPEED_PER_SECOND: Final = 3.7
"""靴を取っていないときの速さ（1秒あたりのマス数）。

原型の値で、選んだ理由の記録は無い。原型はこれに動物ごとの倍率を掛ける（うさぎは
1.22 倍など）。倍率は動物のデータを作る段階 5 で掛ける。いまは全員が倍率 1。
"""

BASE_SPEED: Final = BASE_SPEED_PER_SECOND / TICKS_PER_SECOND
"""靴を取っていないときの速さ（1 tick あたりのマス数）。"""

SHOE_STEP_PER_SECOND: Final = 0.42
"""靴を1つ取るごとに上がる速さ（1秒あたりのマス数）。

取れる段数を増やしたぶん、1段の上がり幅を小さくした（原型の注記）。
"""

SHOE_STEP: Final = SHOE_STEP_PER_SECOND / TICKS_PER_SECOND
"""靴を1つ取るごとに上がる速さ（1 tick あたりのマス数）。"""

MAX_SHOES: Final = 13
"""靴を取れる段数の上限。原型の値で、選んだ理由の記録は無い。"""

MAX_SPEED_PER_SECOND: Final = 9.4
"""速さの上限（1秒あたりのマス数）。

靴を上限の 13 段まで取ると 3.7 + 13 × 0.42 = 9.16 になるので、その上に置いた
（原型の注記）。動物ごとの倍率を掛けない今は、靴を取りきってもこの上限では止まらない。
原型のうさぎ（1.22 倍）は 3.7 × 1.22 + 13 × 0.42 = 9.974 になり、この上限で止まる。

原型の注記は、靴の上限を上げるときは、移動を細かく分ける回数の計算を見るように求めて
いる。1回で大きく動かすと、行き先を1回見るだけの当たり判定が壁を飛び越えるため。原型は
分ける回数を 16 で打ち切るので、最も速い人が毎秒およそ 14 マスを超えると（経過秒数の
上限 0.045 秒・倍速 3 のとき）、1回の移動が 0.12 マスを超える。この版は回数に上限が
無いので、速さの上限を上げても1回の移動は `MOVE_SUBSTEP_DISTANCE` を超えない（決め方の
違いは `systems/movement.py`）。
"""

MAX_SPEED: Final = MAX_SPEED_PER_SECOND / TICKS_PER_SECOND
"""速さの上限（1 tick あたりのマス数）。"""

PLAYER_RADIUS: Final = 0.36
"""移動の当たり判定に使う、プレイヤーの半径（マス）。

0.5 より小さいので、通路の中央にいれば両側の壁に触れない（隙間は 0.14 ずつ）。
原型の値で、選んだ理由の記録は無い。
"""

ALIGN_EPSILON: Final = 0.004
"""通路の中央へ寄せるのをやめる距離（マス）。原型の値で、選んだ理由の記録は無い。"""

ALIGN_RATE_WHEN_MOVING: Final = 0.9
"""進めたときに、通路の中央へ寄せる幅に掛ける倍率。進めなかったときは 1 倍。

原型の値で、選んだ理由の記録は無い。
"""

MOVE_SUBSTEP_DISTANCE: Final = 0.12
"""移動を細かく分けるときの、1回あたりに進む距離の上限（マス）。

原型の注記：1回で大きく動かすと、行き先を1回見るだけの当たり判定が柱を飛び越える
（原型の1回の移動は、経過秒数と倍速を掛けた分なので大きくなりうる）。そこで、当たり
判定を挟む1回の移動をこの距離以下に抑える。この版の 1 tick の移動は最も速くても
0.157 マスで、飛び越えは起きないが、分けると壁の手前で止まる位置が細かくなる
（`systems/movement.py`）。

⚠️ 細かく分けるのは移動の当たり判定だけ。原型は時間を進める処理ごと分けていたため、
導火線の進みも入力の読み取りも一緒に分かれ、倍速にすると1回のキー入力が2〜3回と
して処理された。
"""
