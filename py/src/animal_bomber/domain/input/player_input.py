"""プレイヤーの入力（1 tick ぶんの、押しているボタンの組）。

キーボードやゲームパッドを押しているか、CPU がそう決めたか、通信で届いたか、記録から
流しているかを区別しない。ルールの層は、この形になったものだけを受け取る。CPU の
「押す」は、そう決めたという意味で、人間の押したボタンと同じ形で返す。

原型は、人間の入力は1つの形にまとめていた（inputOf）が、CPU の判断はプレイヤーの座標や
爆弾を直接動かしていた。さらに乱数と経過秒数が決定的でなかったため、記録の流し直しも、
操作だけを送る通信対戦もできなかった（原型の注記）。この版は、人間も CPU もこの型を
返し、乱数と時間を決定的にしてある。この型が1つあることで、記録の流し直し・通信対戦・
画面なしで大量の試合を回すバランスの検証が、同じ仕組みで成り立つ。

## ビットの組（IntFlag）で表す

押しているボタンの組を `enum.IntFlag` で表す。TypeScript 版は真偽値6つの形と、それを
1バイトへ詰める関数・戻す関数の対を持つ。この版は型そのものが1バイトに収まる整数なので、
詰める関数が要らない。`int(player_input)` が記録や通信に書く値で、`PlayerInput(bits)` が
そこから戻した値になる。ビットの並びは TypeScript 版と同じ。

`boundary=STRICT` にしてあるので、0 以上の整数のうち、決めていないビットを含むものから
作ろうとすると `ValueError` になる（既定の `IntFlag` は黙って受け付ける）。壊れた記録や
通信の値を、読んだ時点で止める。

⚠️ 負の整数は STRICT でも補数として受け付ける（-64〜-1。-1 は6つのボタン全部）。
記録や通信の値は符号なしで読むか、読んだ側で 0 未満を断る（記録の文字列は `-` を
読まないので、`net/input_log.py` では起きない。通信の値を読む段階 9 で気をつける）。
"""

from enum import STRICT, IntFlag


class PlayerInput(IntFlag, boundary=STRICT):
    """押しているボタンの組。`PlayerInput.RIGHT | PlayerInput.BOMB` のように重ねる。"""

    IDLE = 0
    """何も押していない。"""
    UP = 1
    DOWN = 2
    LEFT = 4
    RIGHT = 8
    BOMB = 16
    """爆弾のボタン。"""
    ACTION = 32
    """技のボタン。押した瞬間に通常技、押し続けてしきい値に届くととくぎ（段階 5）。"""
