"""台本どおりの試合が、決めておいた状態の要約に行き着くことの検査（固定値）。

リプレイの検査（`test_replay.py`）は、同じプロセスの中で2回走らせて比べる。それでは、
Python の版や実行する機械が変わったときに結果が変わることを捕まえられない。ここでは、
一度出した要約をコードに書いておき、毎回それと比べる。検査（`tools/verify.sh`）は
pytest を 3.12 で走らせたあと、3.11 でもう一度走らせる（`uv run --isolated --python 3.11
pytest` の行）ので、版で結果が変わればどちらかで失敗する。

そのため、リプレイの保存に Python の版を書いておき、違えば流し直しを断る仕組みは
作らない。版で結果が変わるなら、それはルールの層の誤り（版で値が変わる計算を使って
いる）で、ここで見つけて直す。

⚠️ ルールを変えて試合の結果が変わったときは、ここも失敗する。変わることが意図どおり
なら、新しい値を出して書き換え、なぜ変わったかをコミットに書く。意図していなければ、
値を書き換えずに原因を探す。
"""

from animal_bomber.domain.state.world import hash_world

from .scenario import play_and_record, play_match, replay

# 台本どおりに 600 tick 進めたあとの要約（`StateHasher.hex` と同じ 8 桁）。
# 2026-10-04 に Python 3.12 で出し、3.11 でも同じ値になることを確かめた。段階 3 で、
# アイテムとプレイヤーごとの体力・無敵の切れる tick・一時的な状態・とくぎの回数・最後に
# 当てたプレイヤーを要約に足し、台本の盤面にアイテムを並べ、向きのボタンを離す間を足し、
# 種を 4649 から 4658 に替えたので、段階 2 の値（89535742）から変わった。
# そのあと、「勝手に設置」を 0.5 秒に1回にして待ちを要約に足したので（台本では2回
# かかる）、c50eb1f2 から変わった。同じときに入れた重なった爆風の持ち主の直しは、この
# 台本の値を変えない（どちらも原型に合わせた。TypeScript 版は 2ce8030）。
# 爆風を伸ばす向きを原型の順（右・左・下・上）にしても、この値は変わらない。爆風が
# 盤面に残っている間は爆風の並びと識別子が変わるが、600 tick 目には爆風が残っておらず、
# アイテムと乱数を引いた回数も同じになる（新旧の順で tick ごとに比べて確かめた）。
# 勝手に設置を動く前に置く直しも、この台本の値を変えない。
# 段階 5 で a599364a から変わった。動物ごとの上乗せ（速さ・火力・体力・爆弾の数）が
# 効き、技のボタンが技を出すようになり（台本にとくぎの長押しとチキンも足した）、要約に
# 技の振る舞い・長押し・間隔・盤面の物・撒かれた／溶けているアイテムの値を足したため。
# 2026-10-12 に Python 3.12 と 3.11 で出し、同じ値になることを確かめた。
# そのあと、要約に盤面の物の持ち主を足したので（跳ねる爆弾の持ち主が要約から漏れて
# いた）、6de2dc26 から変わった。600 tick 目に盤面の物が残っているため。試合の進み方は
# 変わらない（TypeScript 版と比べる台本は、要約を使わずに行ごとに比べて、そのまま
# 一致する）。ラウンドをまたぐ台本の値（下）は、決まった盤面に盤面の物が残っていない
# ので変わらない。
# そのあと、うんこのアイテムを原型に合わせ（15 秒で消え、爆風で焼けずに吹き飛ぶ）、
# 要約の混ぜ方を「撒かれた・消える時刻・溶けている」の3つを別々に混ぜる形にしたので、
# 366d7a64 から変わった（台本の盤面にうんこを並べているため。ラウンドをまたぐ台本の値は
# 変わらない）。
# そのあと、滑っている間の動きを原型に合わせた（向きを押しても曲がらない・泣いていても
# 技の最中も滑る）ので、5c98859a から変わった（台本の盤面にバナナを並べているため）。
# そのあと、1 tick の中の並びを原型の update と同じにした（プレイヤーごとに動く・置く・
# 拾う、拾うのが爆発より先、状態の時間を技の前に減らす、など）ので、8968763f から
# 変わった。
# そのあと、技のボタンの読み方を原型に合わせ（押した瞬間に通常技・振る舞いの最中も
# ボタンを見る）、要約に混ぜる項目を「押し始めに動けなかったか」から「とくぎを出し
# 終えたか」に替え、ラウンドの始まりは技のボタンも押していた扱いにしたので、332ab4a8
# から変わった。
# 段階 8 で、プレイヤーの状態を閉じた union（盤面・外周・退場）にし、要約に混ぜる名前を
# Enum の名前（"ALIVE"）から状態の名前（"alive"。TypeScript 版の hashLife と同じ）に
# 替えたので、f692e410 から変わった。試合の進み方は変わらない（TypeScript 版と比べる
# 台本は、そのまま tick ごとに一致する）。2026-10-18 に 3.12 と 3.11 で出し、同じ値に
# なることを確かめた。
GOLDEN = "0526e2ee"

# ラウンドをまたぐ台本（`play_match`）を 1500 tick 進めたあとの盤面の要約。段階 4 で
# 足した。1ラウンド目は時間切れ、2ラウンド目は 1P の勝ちで試合が決まり、決まった盤面の
# まま止まっている。決まった盤面には爆風が残っているので、爆風を伸ばす向きを原型の順に
# したとき、ec70ff0f から変わった（勝手に設置を動く前に置く直しは、この値を変えない）。
# 段階 5 で 3db7fbaf から変わった（動物を 1P かえる・うさぎ・もぐら・きつねにし、上の
# 台本と同じく、上乗せと技と要約の足し分が効く）。試合の決まり方（2ラウンド目、
# 1223 tick 目に 1P の勝ち）は変わらない。
# 技のボタンの読み方を原型に合わせたとき（上の台本と同じ理由。要約に混ぜる項目と、
# ラウンドの始まりの前の tick の入力が変わる）、aed2b3f3 から変わった。
# 段階 8 でプレイヤーの状態を閉じた union にしたとき（上の台本と同じ理由。要約に混ぜる
# 名前が変わる）、e10d6fc8 から変わった。試合の決まり方は変わらない。
GOLDEN_MATCH = "79a42b43"


def test_ラウンドをまたぐ台本は_決めておいた要約に行き着く() -> None:
    session = play_match()
    match = session.match
    assert (match.round, match.wins, match.champion, match.finished) == (
        2,
        {0: 1},
        0,
        True,
    )
    assert f"{hash_world(session.world):08x}" == GOLDEN_MATCH


def test_台本どおりの試合は_決めておいた要約に行き着く() -> None:
    played, _ = play_and_record()
    assert f"{hash_world(played):08x}" == GOLDEN


def test_記録を流し直しても_決めておいた要約に行き着く() -> None:
    _, log = play_and_record()
    assert f"{hash_world(replay(log)):08x}" == GOLDEN
